<?php

declare(strict_types=1);

namespace Atannex\ClaudeSupport\Guidelines;

use Atannex\ClaudeSupport\Resources\ResourceDefinition;
use Atannex\ClaudeSupport\Resources\ResourceType;
use Atannex\ClaudeSupport\Stack\Catalog;
use Atannex\ClaudeSupport\Stack\Stack;

/** Renders the body of the managed CLAUDE.md block from detected facts. */
final class GuidelinesRenderer
{
    private const HEADINGS = [
        'commands' => 'Slash commands',
        'agents' => 'Subagents (delegate to them with the Agent tool)',
        'skills' => 'Skills (load automatically when relevant)',
    ];

    /**
     * @param  list<ResourceDefinition>  $resources
     * @param  list<string>  $conventions
     * @param  string|null  $language  the language the team works in, e.g. "French"
     */
    public function render(Stack $stack, array $resources, array $conventions, ?string $language = null): string
    {
        $sections = [
            "## Project context\n\n"
            ."_Generated by atannex/claude-support from this project's manifests. "
            .'Re-run `php artisan claude:install` to refresh it; edits inside this block are overwritten, edits outside it are kept._',
            $this->stack($stack),
            $this->verification($stack),
        ];

        if ($language !== null) {
            $sections[] = "### Language\n\n".$this->list([
                "Communicate with the team in {$language}: explanations, questions, plans, summaries and pull request descriptions.",
                "Keep code, identifiers, comments, commit messages and log output in English unless the surrounding code is already written in {$language}.",
                'User-facing strings belong in lang/ files, never hard-coded, so every locale can be translated.',
            ]);
        }

        if ($conventions !== []) {
            $sections[] = "### Conventions\n\n".$this->list($conventions);
        }

        foreach (ResourceType::cases() as $type) {
            $lines = [];
            foreach ($resources as $resource) {
                if ($resource->type === $type) {
                    $lines[] = "`{$resource->handle()}` — {$resource->description}";
                }
            }

            if ($lines !== []) {
                $sections[] = '### '.self::HEADINGS[$type->value]."\n\n".$this->list($lines);
            }
        }

        return implode("\n\n", $sections);
    }

    private function stack(Stack $stack): string
    {
        $lines = [];

        $runtime = array_filter([
            $stack->php !== null ? "PHP {$stack->php}" : null,
            $stack->laravel !== null ? "Laravel {$stack->laravel}" : null,
        ]);
        if ($runtime !== []) {
            $lines[] = implode(', ', $runtime);
        }

        $lines[] = "Tests: {$stack->testRunner}";

        if ($stack->database !== null) {
            $lines[] = "Default database connection driver: {$stack->database}";
        }

        foreach (Catalog::group(Catalog::NPM, array_fill_keys($stack->frontend, '')) as $category => $labels) {
            $lines[] = "Frontend — {$category}: ".implode(', ', array_keys($labels));
        }

        foreach (Catalog::group(Catalog::COMPOSER, $stack->packages) as $category => $versions) {
            $named = [];
            foreach ($versions as $label => $version) {
                $named[] = $version !== '' ? "{$label} ({$version})" : $label;
            }
            $lines[] = "Packages — {$category}: ".implode(', ', $named);
        }

        return "### Stack\n\n".$this->list($lines);
    }

    private function verification(Stack $stack): string
    {
        $lines = ['Tests: `php artisan test`'.($stack->hasComposerScript('test') ? ' (or `composer test`)' : '')];

        if ($stack->pint) {
            $lines[] = 'Formatting: `vendor/bin/pint --dirty` before finishing';
        }

        if ($stack->phpstan) {
            $lines[] = 'Static analysis: `vendor/bin/phpstan analyse`';
        }

        return "### Verify your work\n\n".$this->list($lines);
    }

    /** @param  list<string>  $items */
    private function list(array $items): string
    {
        return implode("\n", array_map(fn (string $item): string => "- {$item}", $items));
    }
}
